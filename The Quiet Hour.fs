FILMSCRIPT 1
title: The Quiet Hour

fadein: FADE IN:

scene: INT. RADIO STATION. NIGHT
action: A single lamp. NOA (40s, unhurried) leans into the microphone. Rain taps the window like a listener asking to come in.
character: NOA
paren: (into the mic)
dialogue: If you are still awake, this hour is yours.
action: She slides a fader down. The city hum fades under her voice.

scene: EXT. EMPTY STREET. CONTINUOUS
action: Wet asphalt mirrors the streetlights. A radio glows in a parked taxi,
  the driver asleep against the window.
character: NOA (V.O.)
dialogue: Tonight, a request from someone who did not leave a name.
transition: CUT TO:

scene: INT. RADIO STATION. LATER
action: Noa watches the phone line blink. She does not answer it yet.
character: NOA
paren: (quietly)
dialogue: Some songs you play for the living. This one goes out to the rest.

end: THE END
